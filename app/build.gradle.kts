/**
 * Secrets are never committed. They are resolved, in order, from:
 * 1. `local.properties` (git-ignored, recommended for local development)
 * 2. Gradle properties (`-PRAPIDAPI_KEY=...` or `~/.gradle/gradle.properties`)
 * 3. Environment variables (useful for CI)
 */
val localProperties = Properties().apply {
    providers.fileContents(rootProject.layout.projectDirectory.file("local.properties"))
        .asText.orNull
        ?.let { load(it.reader()) }
}

fun secret(name: String): String =
    localProperties.getProperty(name)
        ?: providers.gradleProperty(name).orNull
        ?: providers.environmentVariable(name).orNull
        ?: ""

